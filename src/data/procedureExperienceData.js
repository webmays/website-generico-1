/**
 * Retorna a lista de itens da experiência enriquecida com narrativa emocional e requinte.
 */
export function getProcedureExperience(procedure) {
  if (!procedure) return [];

  // Se já houver mapeamento manual detalhado para este slug:
  if (PROCEDURE_EXPERIENCE_MAP[procedure.slug]) {
    return PROCEDURE_EXPERIENCE_MAP[procedure.slug];
  }

  // Fallback inteligente caso novos procedimentos sejam adicionados:
  const baseItems = procedure.includes || [];
  return baseItems.map((item, idx) => {
    const isSpecial =
      item.toLowerCase().includes("kit") ||
      item.toLowerCase().includes("mimo") ||
      item.toLowerCase().includes("cappuccino") ||
      item.toLowerCase().includes("café") ||
      item.toLowerCase().includes("massagem") ||
      item.toLowerCase().includes("spa");

    return {
      num: String(idx + 1).padStart(2, "0"),
      title: item,
      desc: `Etapa executada com materiais de alta qualidade e carinho meticuloso para transformar seu momento em pura expressão de beleza e conforto.`,
      badge: isSpecial ? "Destaque Exclusivo" : `Etapa ${idx + 1}`,
      isSpecial
    };
  });
}
